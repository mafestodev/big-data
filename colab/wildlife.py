# --------------------------------------------------
# 3. LOAD EXISTING EMBEDDINGS
# --------------------------------------------------

with np.load(gallery_path, allow_pickle=False) as data:
    gallery_np = data["embeddings"].astype(np.float32)
    gallery_ids = data["identities"]

with np.load(query_path, allow_pickle=False) as data:
    query_np = data["embeddings"].astype(np.float32)
    query_ids = data["identities"]

# Basic data validation
assert gallery_np.ndim == 2, "Gallery embeddings must be 2D."
assert query_np.ndim == 2, "Query embeddings must be 2D."
assert gallery_np.shape[1] == query_np.shape[1], (
    "Gallery and query embedding dimensions do not match."
)
assert len(gallery_np) == len(gallery_ids), (
    "Gallery embedding and identity counts do not match."
)
assert len(query_np) == len(query_ids), (
    "Query embedding and identity counts do not match."
)
assert len(gallery_np) > 0, "Gallery is empty."
assert len(query_np) > 0, "Query set is empty."

print("\nLoaded embeddings successfully.")
print(f"Gallery images: {len(gallery_ids):,}")
print(f"Test queries: {len(query_ids):,}")
print(f"Embedding dimensions: {gallery_np.shape[1]}")

# --------------------------------------------------
# 4. NORMALIZE EMBEDDINGS FOR COSINE SIMILARITY
# --------------------------------------------------

gallery = torch.from_numpy(gallery_np).to(device)
queries = torch.from_numpy(query_np).to(device)

gallery = torch.nn.functional.normalize(gallery, dim=1)
queries = torch.nn.functional.normalize(queries, dim=1)

# --------------------------------------------------
# 5. IDENTIFY KNOWN AND UNSEEN QUERY IDENTITIES
# --------------------------------------------------

gallery_set = set(gallery_ids.tolist())

covered = np.array(
    [query_id in gallery_set for query_id in query_ids],
    dtype=bool
)

closed_count = int(covered.sum())
unseen_count = int((~covered).sum())

if closed_count == 0:
    raise ValueError(
        "No query identities occur in the gallery. "
        "Closed-set metrics cannot be calculated."
    )

print("\nIdentity coverage:")
print(
    f"Known-identity queries: {closed_count:,} "
    f"({100 * covered.mean():.2f}%)"
)
print(
    f"Unseen-identity queries: {unseen_count:,} "
    f"({100 * (~covered).mean():.2f}%)"
)

# --------------------------------------------------
# 6. CALCULATE CLOSED-SET RETRIEVAL METRICS
# --------------------------------------------------
# Only queries whose identities occur in the gallery
# contribute to these closed-set metrics.
#
# Top-1: correct identity at rank 1.
# Top-5: correct identity appears within the first 5.
# Precision@5: fraction of the first 5 images matching
#              the query identity.
# AP: average precision across the ranked gallery.
# mAP: mean AP across known-identity queries.
#
# IMPORTANT:
# This assumes query images do not also appear as
# gallery images. Verify that the underlying splits
# are image-disjoint before reporting final results.

top1_hits = 0
top5_hits = 0
precision5_sum = 0.0
ap_sum = 0.0

chunk_size = 16
gallery_size = len(gallery_ids)

print("\nCalculating validated metrics...")

for start_idx in range(0, len(query_ids), chunk_size):
    end_idx = min(start_idx + chunk_size, len(query_ids))

    # Compute cosine similarities for this query chunk.
    with torch.inference_mode():
        similarities = queries[start_idx:end_idx] @ gallery.T

        # Rank gallery images from highest to lowest similarity.
        ranked_indices = torch.argsort(
            similarities,
            dim=1,
            descending=True
        ).cpu().numpy()

    # Calculate metrics for each query in this chunk.
    for local_idx, indices in enumerate(ranked_indices):
        query_idx = start_idx + local_idx

        # Exclude identities not represented in the gallery.
        if not covered[query_idx]:
            continue

        ranked_ids = gallery_ids[indices]
        relevant = ranked_ids == query_ids[query_idx]

        # Guard against queries with no relevant gallery images.
        num_relevant = int(relevant.sum())
        assert num_relevant > 0, (
            f"No relevant gallery images for query index {query_idx}."
        )

        # Top-1 and Top-5 identification accuracy.
        top1_hits += int(relevant[0])
        top5_hits += int(relevant[:5].any())

        # Precision at rank 5.
        precision5_sum += float(relevant[:5].mean())

        # Average Precision for this query.
        hits = np.cumsum(relevant)
        ranks = np.arange(1, len(relevant) + 1)

        average_precision = (
            np.sum((hits / ranks) * relevant) / num_relevant
        )

        ap_sum += float(average_precision)

    if start_idx % 2048 == 0 or end_idx == len(query_ids):
        print(f"Processed {end_idx:,}/{len(query_ids):,} queries")

# --------------------------------------------------
# 7. SUMMARIZE METRICS
# --------------------------------------------------

top1 = 100.0 * top1_hits / closed_count
top5 = 100.0 * top5_hits / closed_count
precision5 = 100.0 * precision5_sum / closed_count
map_score = 100.0 * ap_sum / closed_count

runtime_minutes = (time.time() - start_time) / 60.0

