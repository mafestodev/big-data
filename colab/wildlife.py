# Step 7 - Memory-efficient wildlife re-identification evaluation


import time
import numpy as np
import torch
from pathlib import Path

start_time = time.time()

GALLERY_PATH = Path(
    "/content/drive/MyDrive/WildlifeReID/gallery/embeddings.npz"
)
QUERY_PATH = Path(
    "/content/drive/MyDrive/WildlifeReID/gallery/query_embeddings.npz"
)
REPORT_PATH = Path(
    "/content/drive/MyDrive/WildlifeReID/evaluation_results.txt"
)

assert GALLERY_PATH.exists(), f"Gallery missing: {GALLERY_PATH}"
assert QUERY_PATH.exists(), f"Queries missing: {QUERY_PATH}"
assert torch.cuda.is_available(), "Colab GPU is not enabled. Select a GPU runtime."

# Load existing embeddings.
with np.load(GALLERY_PATH, allow_pickle=False) as data:
    gallery_np = data["embeddings"].astype(np.float32)
    gallery_ids = data["identities"]

with np.load(QUERY_PATH, allow_pickle=False) as data:
    query_np = data["embeddings"].astype(np.float32)
    query_ids = data["identities"]

assert gallery_np.ndim == 2 and query_np.ndim == 2
assert gallery_np.shape[1] == query_np.shape[1], "Embedding dimensions differ"
assert len(gallery_np) == len(gallery_ids)
assert len(query_np) == len(query_ids)
assert len(query_np) > 0 and len(gallery_np) > 0

device = torch.device("cuda")
print("Device:", torch.cuda.get_device_name(0))
print(f"Gallery images: {len(gallery_np):,}")
print(f"Test queries:   {len(query_np):,}")
print(f"Embedding size: {gallery_np.shape[1]}")
print("Preparing embeddings...")

# Move normalized embeddings to GPU.
gallery = torch.from_numpy(gallery_np).to(device)
queries = torch.from_numpy(query_np).to(device)

gallery = torch.nn.functional.normalize(gallery, p=2, dim=1)
queries = torch.nn.functional.normalize(queries, p=2, dim=1)

# Keep labels on CPU; only the similarity calculation and ranking use GPU.
gallery_labels = gallery_ids
query_labels = query_ids

gallery_identity_set = set(gallery_labels.tolist())
covered = np.array([
    identity in gallery_identity_set for identity in query_labels
])

top1_hits = 0
top5_hits = 0
precision5_total = 0.0
ap_total = 0.0
ap_queries = 0

# Small query chunks keep GPU memory use manageable.
chunk_size = 16
gallery_count = len(gallery_labels)

print("Evaluating queries...")

for start in range(0, len(query_labels), chunk_size):
    end = min(start + chunk_size, len(query_labels))

    # Only a chunk_size × gallery_count similarity matrix is created.
    with torch.inference_mode():
        similarities = queries[start:end] @ gallery.T
        top_indices = torch.argsort(
            similarities, dim=1, descending=True
        )

    # Transfer ranked indices to CPU for identity metrics.
    ranked_indices = top_indices.cpu().numpy()

    for local_idx, indices in enumerate(ranked_indices):
        true_id = query_labels[start + local_idx]
        ranked_ids = gallery_labels[indices]
        relevant = (ranked_ids == true_id)
        total_relevant = int(relevant.sum())

        top1_hits += int(relevant[0])
        top5_hits += int(relevant[:5].any())
        precision5_total += float(relevant[:5].mean())

        # AP is defined only for queries with relevant gallery images.
        if total_relevant > 0:
            hits_so_far = np.cumsum(relevant)
            ranks = np.arange(1, gallery_count + 1)
            ap = np.sum(
                (hits_so_far / ranks) * relevant
            ) / total_relevant
            ap_total += float(ap)
            ap_queries += 1

    del similarities, top_indices

    if end % 512 == 0 or end == len(query_labels):
        elapsed = (time.time() - start_time) / 60
        print(
            f"Processed {end:,}/{len(query_labels):,} queries "
            f"({end / len(query_labels) * 100:.1f}%) "
            f"| elapsed {elapsed:.1f} min"
        )

n = len(query_labels)

top1 = top1_hits / n
top5 = top5_hits / n
precision5 = precision5_total / n
map_score = ap_total / ap_queries if ap_queries else float("nan")

results = [
    "WILDLIFE RE-IDENTIFICATION EVALUATION",
    "=" * 42,
    "Checkpoint: swin_embedding_model_epoch_16.pt",
    f"Gallery images: {len(gallery_labels):,}",
    f"Test queries: {n:,}",
    f"Embedding dimensions: {gallery_np.shape[1]}",
    f"Queries whose identity exists in gallery: "
    f"{covered.sum():,}/{n:,} ({covered.mean() * 100:.2f}%)",
    "",
    f"Top-1 accuracy: {top1 * 100:.2f}%",
    f"Top-5 accuracy: {top5 * 100:.2f}%",
    f"Precision@5: {precision5 * 100:.2f}%",
    f"mAP: {map_score * 100:.2f}%" if ap_queries else "mAP: N/A",
    f"Queries included in mAP: {ap_queries:,}/{n:,}",
    f"Runtime: {(time.time() - start_time) / 60:.1f} minutes",
]

report = "\n".join(results)
print("\n" + report)

REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
REPORT_PATH.write_text(report + "\n", encoding="utf-8")
print("\nReport saved to:", REPORT_PATH)

